"""settings -> AIMM config.toml. The panel is the only writer of config.toml; AIMM hot-reloads it on change."""
import hashlib, json, os, re
from datetime import datetime

HEADER = "# GENERATED by the Marketplace Monitor control panel. Manual edits are overwritten.\n"


def q(s):
    """TOML basic string. JSON escapes are a subset TOML accepts; DEL must also be escaped."""
    return json.dumps(str(s), ensure_ascii=False).replace("\x7f", "\\u007f")


def ql(items):
    return "[" + ", ".join(q(i) for i in items) + "]"


def mins(n):
    return f"{int(n)}m"


# AIMM opens every AI prompt with "A user wants to buy a <item section name>", and the section name is our internal id (p2). Seen live on
# 2026-10-20: the model read "p2" as a product model ("not the SodaStream P2 the user wants"), and read the phrases joined with "and" as one
# combined product (פחית+שתייה+זירו -> "a Zero drink can"). A first, tolerant version of these rules (20 Oct 16:40) then let through a
# clearance post titled only "למכירה" (an air purifier photo; "SodaStream 50₪" was one line among five items) as a 4 = Good match.
# The rules below are generic (nothing product-specific): identity first, from evidence in the text only, and preferences never assumed.
# PROMPT_VERSION is part of the text, so a rules change also changes AIMM's AI-cache key (item config hash) and old verdicts are not reused.
PROMPT_VERSION = 3


def extra_prompt(p):
    return (f'[relevance rules v{PROMPT_VERSION}] Context: "{p["id"]}" above is only an internal search ID, not a product or model name. '
            f'The user named this search "{p["name"]}". The listings are second-hand marketplace posts, often in Hebrew. You only see the '
            "listing's text (title, description, price, condition, location): no photos. The search phrases are alternative ways to find the "
            "same product: a listing needs to be that product, not to contain every phrase. Brand and model names may appear in Hebrew, English, "
            "transliteration or with spelling variations; that is still the product.\n"
            "First decide what is actually being sold, using only evidence in the text. Then judge:\n"
            "- Product identity is the hard requirement. A search word appearing somewhere is not enough: the text must show that the product "
            "itself is offered. Evidence may be in the title or only in the description; a short title such as the brand name alone is fine "
            "when nothing contradicts it.\n"
            "- A generic title (for example \"למכירה\", \"למכירה דחוף\", \"מציאה\", \"for sale\") is not evidence of anything. With a "
            "description that does not clearly identify the product either, the product is unknown.\n"
            "- A post that sells several different items, where the product is one line among others with no details of its own, is weak "
            "evidence: the photo, title, condition and price may belong to another item.\n"
            "- Only a spare part, refill or accessory of the product (unless the search is for that part), or a different product that merely "
            "shares a word with the search, is not the product. A bundle of the product with extra accessories is the product.\n"
            "- The user's Description is preferences, not requirements. Never state that a preference (included items, condition, age, model) "
            "is met unless the listing says so; unknown is unknown.")


def rating_prompt(lang):
    summary = "in Hebrew (natural, short Hebrew; keep prices, model names and quoted listing text as written)" if lang == "he" else "in English"
    return ("Rate from 1 to 5:\n"
            "1 - Not the requested product: a different product, only a part or accessory of it, or a generic listing whose text never "
            "identifies the product.\n"
            "2 - Unclear: the product is mentioned, but the text does not show that it is what is being sold.\n"
            "3 - Uncertain or weak: the product is probably offered, but the evidence is thin (for example one line in a multi-item post with no "
            "details of its own), or it clearly conflicts with an important preference.\n"
            "4 - Good match: the text clearly shows that the requested product is for sale; some preferences may be unknown.\n"
            "5 - Great deal: clearly the requested product, and the text confirms the important preferences, or the price is excellent for what "
            "is clearly described.\n"
            "End with exactly one final line, and do not use the word Rating anywhere else:\n"
            '"Rating <1-5>: <summary>"\n'
            f"where <1-5> is the rating digit and <summary> is a brief reason (max 30 words) {summary}. Keep the word \"Rating\" and the digit "
            "exactly in this form. Claim only what the listing text states.")


def item_block(p, fb, feedback_block="", ui_lang="he"):
    lines = [f"[item.{p['id']}]", f"enabled = {'true' if p['enabled'] else 'false'}", f"search_phrases = {ql(p['search_phrases'])}",
             f"extra_prompt = {q(extra_prompt(p))}", f"rating_prompt = {q(rating_prompt(ui_lang))}"]
    if p["keywords"]:
        lines.append(f"keywords = {ql(p['keywords'])}")
    if p["antikeywords"]:
        lines.append(f"antikeywords = {ql(p['antikeywords'])}")
    desc = p["description"]
    if feedback_block:
        desc = (desc + "\n" + feedback_block).strip()
    if desc:
        lines.append(f"description = {q(desc)}")
    if p["min_price"] is not None:
        lines.append(f"min_price = {p['min_price']}")
    if p["max_price"] is not None:
        lines.append(f"max_price = {p['max_price']}")
    city = p["search_city"] or (fb["search_city"] if p["radius"] is not None else "")
    if city:  # AIMM rejects a per-search radius without a per-search city, so the general city is written next to it
        lines.append(f"search_city = {q(city)}")
    if p["radius"] is not None:
        lines.append(f"radius = {p['radius']}")
    if p["rating"] is not None:
        lines.append(f"rating = {p['rating']}")
    if p["search_interval_min"] is not None:
        lines.append(f"search_interval = {q(mins(p['search_interval_min']))}")
    if p["condition"]:
        lines.append(f"condition = {ql(p['condition'])}")
    if p["date_listed"]:
        lines.append(f"date_listed = {p['date_listed']}")
    if p["delivery_method"] != "all":
        lines.append(f"delivery_method = {q(p['delivery_method'])}")
    return "\n".join(lines)


# AIMM 0.10.2 reads English Facebook text and ships translations only for es/zh/sv. These Hebrew strings are what Facebook shows on a
# Hebrew account. VERIFIED on the real Hebrew pages (2026-10-03): the first four. The rest are best-effort and only used on pages
# that have those sections.
HE_TRANSLATION = [
    ("Collection of Marketplace items", "אוסף פריטי Marketplace", True), ("Condition", "מצב", True), ("Details", "פרטים", True),
    ("Location is approximate", "המיקום הוא משוער", True), ("Description", "תיאור", False), ("About this vehicle", "מידע על הרכב", False),
    ("Seller's description", "תיאור המוכר", False), ("Browse Marketplace", "עיון ב-Marketplace", False), ("See more", "ראה עוד", False), ("See less", "ראה פחות", False),
]


def build(settings, guard_token, ntfy_server="http://ntfy-to-telegram:8080", feedback_for=lambda key: "", language=None):
    ui_lang = (settings.get("ui") or {}).get("language", "he")  # the language of the AI's explanations; the scale and parser do not change
    fb = settings["facebook"]
    out = [HEADER, "[marketplace.facebook]"]
    if fb["search_city"]:
        out.append(f"search_city = {q(fb['search_city'])}")
    if fb["search_city"]:  # AIMM rejects radius and currency without a city
        out += [f"radius = {fb['radius']}", f"currency = {q(fb['currency'])}"]
    out += [f"search_interval = {q(mins(fb['search_interval_min']))}",
            f"max_search_interval = {q(mins(fb['max_search_interval_min']))}", f"rating = {fb['rating']}", "login_wait_time = 3",
            "ai = ['guard']", "notify = ['marketplace']"]
    if language == "he":
        out.append('language = "he"')
    out += ["", "[ai.guard]", "provider = 'openai'", "base_url = 'http://gemini-guard:8090/v1'", f"api_key = {q(guard_token)}",
            "model = 'ignored-guard-pins-the-model'", "max_retries = 2", "timeout = 240", "",
            "[user.marketplace]", f"ntfy_server = {q(ntfy_server)}", "ntfy_topic = 'marketplace'", ""]
    if language == "he":
        out += ["[translation.he]", 'locale = "Hebrew"'] + [f"{q(k)} = {q(v)}" for k, v, _ in HE_TRANSLATION] + [""]
    for p in settings["products"]:
        out += [item_block(p, fb, feedback_for(p["id"]), ui_lang), ""]
    return "\n".join(out)


def fingerprint(text):
    return hashlib.sha256(text.encode()).hexdigest()[:16]
